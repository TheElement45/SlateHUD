# Pure shortcut discovery helpers. This file never launches apps or changes shortcuts.
function Get-AppShortcutIndex {
    param([string[]]$Folders)
    $links = @{}
    foreach ($folder in $Folders) {
        if (-not (Test-Path -LiteralPath $folder -PathType Container)) { continue }
        foreach ($file in Get-ChildItem -LiteralPath $folder -File | Sort-Object Name) {
            if ($file.Extension -in '.lnk','.url') { $links[$file.BaseName] = $file.FullName }
        }
    }
    return $links
}

function Get-AppCategories {
    return @('Communication','Development','Creative','Utilities','System','Productivity')
}

function Get-AppCategory([string]$Name) {
    if ($Name -match '(?i)git bash|visual studio|vscode|eclipse|antigravity|pycharm|intellij|notepad\+\+') { return 'Development' }
    if ($Name -match '(?i)discord|whatsapp|telegram|brave|microsoft edge|firefox|chrome|signal|slack|zoom') { return 'Communication' }
    if ($Name -match '(?i)media player|music|spotify|vlc|obs studio|resolve|photoshop|blender|audacity|wallpaper|peace') { return 'Creative' }
    if ($Name -match '(?i)crystaldisk(info|mark)|wiztree|msi afterburner|flydigi|nvidia app|revo uninstaller|superposition|windhawk|hwinfo|hwmonitor|gpu-z|cpu-z|occt|aida64|speccy|geekbench|cinebench') { return 'System' }
    if ($Name -match '(?i)google (docs|sheets|slides|drive)|microsoft (word|excel|powerpoint|onenote|office)|\b(word|excel|powerpoint|onenote|outlook|notion|obsidian|todoist|trello|gemini|pdfgear|libreoffice)\b') { return 'Productivity' }
    return 'Utilities'
}

function Get-AppRows {
    param([hashtable]$Links,[object[]]$ConfiguredRows,[string]$DiscoveryFolder)
    $known = @{}
    foreach ($row in $ConfiguredRows) {
        $known[$row.Shortcut] = $true
        if ($row.Secondary) { $known[$row.Secondary] = $true }
    }
    foreach ($row in $ConfiguredRows) {
        if ($row.Category -notin (Get-AppCategories)) { throw 'Unknown app category in Shortcuts.csv.' }
        if ($Links.ContainsKey($row.Shortcut)) { Write-Output $row }
    }
    # Only opt-in additions inside Apps are auto-discovered. Desktop roots are
    # still searched for configured entries, but unrelated desktop items stay out.
    $folderPath = [IO.Path]::GetFullPath($DiscoveryFolder).TrimEnd('\')
    foreach ($name in $Links.Keys | Sort-Object) {
        if ($known.ContainsKey($name)) { continue }
        if ([IO.Path]::GetDirectoryName($Links[$name]).TrimEnd('\') -ne $folderPath) { continue }
        [pscustomobject]@{Shortcut=$name;Label=$name;Category=(Get-AppCategory $name);Favorite='0';Secondary=''}
    }
}

function Get-AppShortcutKey([string]$Name) {
    $hash = [Security.Cryptography.SHA256]::Create()
    try {
        return ([BitConverter]::ToString($hash.ComputeHash([Text.Encoding]::UTF8.GetBytes($Name.ToLowerInvariant())))).Replace('-','').ToLowerInvariant()
    } finally { $hash.Dispose() }
}

function Convert-IniText([string]$value) {
    # Display data must not become variables, section references, or actions.
    return $value.Replace('#',[string][char]0xFF03).Replace('[',[string][char]0xFF3B).Replace(']',[string][char]0xFF3D).Replace('"',"'") -replace '[\r\n\t]', ' '
}

function Get-LaunchAction([string]$path) {
    if ($path -match '[\[\]#"\r\n]') { throw 'A shortcut path contains unsupported Rainmeter characters.' }
    return '["' + $path + '"]'
}

function New-AppCatalogText {
    param([object[]]$Records,[string]$ShortcutFolder,[int]$Warnings=0)
    $text = [Text.StringBuilder]::new()
    [void]$text.AppendLine('; Generated by ScanApps.ps1. Edit Shortcuts.csv for defaults; use app menus for personal overrides.')
    [void]$text.AppendLine('[Variables]')
    [void]$text.AppendLine('AppCount=' + $Records.Count)
    [void]$text.AppendLine('AppShortcutFolder=' + $ShortcutFolder)
    [void]$text.AppendLine('AppScanWarnings=' + $Warnings)
    foreach ($app in $Records) {
        foreach ($field in 'Key','Name','Label','Path','Category','Favorite','SecondaryAction') {
            [void]$text.AppendLine($app.Id + $field + '=' + $app.$field)
        }
    }
    foreach ($app in $Records) {
        $id = $app.Id
        foreach ($part in 'Hit','Icon','Label','Profile') {
            [void]$text.AppendLine("`n[$id$part]")
            [void]$text.AppendLine('Meter=' + $(if ($part -in 'Label','Profile') { 'String' } else { 'Image' }))
            [void]$text.AppendLine('MeterStyle=' + $(if ($part -in 'Label','Profile') { 'StyleAppLabel' } else { 'StyleAppHit' }))
            [void]$text.AppendLine('Group=' + $id)
            switch ($part) {
                Hit { [void]$text.AppendLine('W=(70*#UiScale#)'); [void]$text.AppendLine('H=(70*#UiScale#)') }
                Icon {
                    [void]$text.AppendLine('ImageName=' + $app.Icon)
                    [void]$text.AppendLine('W=(32*#UiScale#)'); [void]$text.AppendLine('H=(32*#UiScale#)')
                    [void]$text.AppendLine('PreserveAspectRatio=1')
                }
                Label {
                    [void]$text.AppendLine('Text=' + $app.Label)
                    [void]$text.AppendLine('W=(70*#UiScale#)'); [void]$text.AppendLine('H=(28*#UiScale#)')
                }
                Profile {
                    [void]$text.AppendLine('Text=[\x25BE]')
                    [void]$text.AppendLine('W=(12*#UiScale#)'); [void]$text.AppendLine('H=(14*#UiScale#)')
                    [void]$text.AppendLine('FontColor=#ColorAccent#')
                    [void]$text.AppendLine('SolidColor=0,0,0,1')
                    [void]$text.AppendLine('MouseActionCursor=1')
                }
            }
            [void]$text.AppendLine('ToolTipText=' + $(if ($part -eq 'Profile') { 'Open Personal profile' } else { $app.Name + '#CRLF#Right-click: app options' }))
            [void]$text.AppendLine('LeftMouseUpAction=' + $(if ($part -eq 'Profile') { '[!CommandMeasure MeasureApps "LaunchSecondary(''' + $id + ''')"]' } else { $app.Action }))
            [void]$text.AppendLine('RightMouseUpAction=[!CommandMeasure MeasureApps "OpenMenu(''' + $id + ''')"]')
            [void]$text.AppendLine('MouseOverAction=[!CommandMeasure MeasureApps "Hover(''' + $id + ''')"]')
            [void]$text.AppendLine('MouseLeaveAction=[!CommandMeasure MeasureApps "Leave(''' + $id + ''')"]')
        }
    }
    return $text.ToString()
}
